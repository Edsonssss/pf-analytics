def verdict_badge(a):
    v = a['verdict']; t = a['score']['total']
    if t >= 10: return '<span class="badge b-buy">бычий</span>'
    if t >= 6: return '<span class="badge b-buy">умеренно бычий</span>'
    if t >= 1: return '<span class="badge b-hold">нейтрально-бычий</span>'
    if t >= -3: return '<span class="badge b-neu">нейтральный</span>'
    return '<span class="badge b-sell">медвежий</span>'

def zone(t, lv):
    if not lv: return '—'
    if abs(lv['hi']-lv['lo']) < max(1e-12, lv['p']*0.0005):
        return P(t, lv['p'])
    return '%s–%s' % (P(t, lv['lo']), P(t, lv['hi']))

def nearest_sup(a):
    """первая зона, целиком лежащая ниже цены"""
    for z in a['sup']:
        if z['hi'] < a['px']*0.9995:
            return z, (1 - z['hi']/a['px'])*100
    return None, None

def nearest_res(a):
    for z in a['res']:
        if z['lo'] > a['px']*1.0005:
            return z, (z['lo']/a['px'] - 1)*100
    return None, None

def updown(a):
    rz, up = nearest_res(a)
    sz, dn = nearest_sup(a)
    return up, dn

def auto_action(t):
    a = TA[t]; p = BY_T[t]
    up, dn = updown(a)
    sc = a['score']['total']
    tgt = p['target']; px = a['px']
    upside = (tgt/px-1)*100 if tgt else None
    ob = a['overbought'] or a['above_bb']
    e1 = a['entry1']
    why = []
    if upside is None and p['dy'] == 0:
        txt, cls = 'Спекулятивно: держать с жёстким стопом, не докупать', 'b-neu'
        why.append('нет ни прогноза аналитиков, ни дивидендов — позиция держится только на техническом импульсе')
        why.append('если импульс сломается (закрытие ниже %s ₽), логично переложить деньги в историю с выплатой' % P(t, a['stop']))
    elif upside is not None and upside < 3:
        txt, cls = 'Цель аналитиков достигнута — частично фиксировать', 'b-fix'
        why.append('цель Т-Банка %s ₽ против цены %s ₽: потенциал %s, дальше рост должен идти через пересмотр таргетов'
                   % (nf(tgt, 1), P(t, px), pf(upside, 1)))
        why.append('разумно продать 20–40%% позиции у сопротивления %s ₽ и держать остаток с трейлингом по SMA20 (%s ₽)'
                   % (P(t, a['r1']), P(t, a['sma20'])))
    elif sc >= 8 and ob:
        if upside is None or upside >= 15:
            txt, cls = 'Держать и докупать по лимитке ниже рынка', 'b-buy'
            why.append('тренд сильный (скор %+d), но бумага перекуплена (стохастик %s, RSI %s) — в рынок не заходим'
                       % (sc, nf(a['stoch_k'], 0), nf(a['rsi'], 0)))
            why.append('лимитные заявки на откат: %s ₽ → %s ₽%s'
                       % (P(t, e1), P(t, a['entry2']),
                          (' → ' + P(t, a['entry3']) + ' ₽') if a.get('entry3') else ''))
        else:
            txt, cls = 'Держать, частично фиксировать у сопротивления', 'b-fix'
            why.append('перекупленность при ограниченном потенциале (%s к цели) — фиксируем часть у %s ₽'
                       % (pf(upside, 1) if upside else '—', P(t, a['r1'])))
    elif sc >= 8 and ((up and dn and up/dn >= 1.3) or (a.get('rr2') or 0) >= 1.2):
        txt, cls = 'Докупать на откате', 'b-buy'
        why.append('сильный тренд (скор %+d) без перекупленности: вверх до ближайшего сопротивления %s, вниз до поддержки %s'
                   % (sc, pf(up, 1, False), pf(dn, 1, False)))
        why.append('сделка от %s ₽ до цели %s ₽ при стопе %s ₽ даёт R/R %s — математика в пользу покупки'
                   % (P(t, a['entry1']), P(t, a['t2']), P(t, a['stop']), nf(a.get('rr2'), 1)))
        why.append('заявки: %s ₽ (40%%) → %s ₽ (35%%), стоп по закрытию дня ниже %s ₽'
                   % (P(t, e1), P(t, a['entry2']), P(t, a['stop'])))
    elif sc >= 4:
        txt, cls = ('Держать / докупать у поддержки', 'b-hold') if not ob else ('Держать, не докупать', 'b-hold')
        why.append('умеренно бычья структура (скор %+d): набираем только от уровней поддержки, не «в рынок»' % sc)
        if ob: why.append('бумага перегрета — новая порция здесь неуместна')
        if dn and dn > 8: why.append('до ближайшей реальной поддержки %s — уровень «висит» без опоры' % pf(dn, 1))
    elif upside is not None and upside >= 20:
        txt, cls = 'Наблюдать: ждём разворота вверх', 'b-neu'
        why.append('фундаментальный потенциал %s к цели есть, но техническая картина слабая (скор %+d) — нужен разворот выше SMA20 (%s ₽)'
                   % (pf(upside, 1), sc, P(t, a['sma20'])))
    else:
        txt, cls = 'Держать под наблюдением / кандидат на замену', 'b-sell'
        why.append('скор %+d: ни тренда, ни перепроданности; деньги могут работать эффективнее в другой позиции' % sc)
    if p['dy'] >= 12 and sc >= 4 and cls not in ('b-sell',):
        why.append('дивдоходность %s%% — держать через отсечку (%s) выгодно' % (nf(p['dy'], 1), p['cut']))
    return txt, cls, why

