def auto_panel(body):
    """заворачивает каждую секцию <h2>…</h2> в белую .panel, как на исходном сайте портфеля"""
    parts = re.split(r'(?=<h2)', body)
    out = []
    for p in parts:
        if p.startswith('<h2'):
            out.append('<div class="panel">' + p.rstrip() + '</div>')
        else:
            out.append(p)
    return '\n'.join(out)

