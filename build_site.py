def zone(t, lv):
    if not lv: return '—'
    if abs(lv['hi']-lv['lo']) < max(1e-12, lv['p']*0.0005):
        return P(t, lv['p'])
    return '%s–%s' % (P(t, lv['lo']), P(t, lv['hi']))

def nearest_sup(a):
    """первая зона, целиком лежащая ниже цены"""
    for z in a['sup']:
        if z['hi'] < a['px']*0.9995:
            return z, (1 - z['hi']/a['px'])*100
    return None, None

def nearest_res(a):
    for z in a['res']:
        if z['lo'] > a['px']*1.0005:
            return z, (z['lo']/a['px'] - 1)*100
    return None, None

def updown(a):
    rz, up = nearest_res(a)
    sz, dn = nearest_sup(a)
    return up, dn

